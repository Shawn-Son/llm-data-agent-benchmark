"""Do wrong answers repeat across runs? (run where all five runs.csv files with answers exist, i.e. Great Lakes)

    python experiments/answer_recurrence.py OUT.md

For each question, the "final value" of every run is extracted from its answer (the bold or 'Answer:' value, else the
first line); a question whose wrong runs give the same final value is a systematic failure (the same misreading every
time), one whose wrong runs disagree is unstable. Reported for the 22 never-right questions and as counts overall.
"""
import csv, re, sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = {'t1': 'haiku-claude-104x3/trial1', 't2': 'haiku-claude-104x3/trial2', 'fdj': 'haiku-claude-fdj-104x3/trial1',
        'docetl': 'haiku-claude-docetl-104x3/trial1', 'sqlverify': 'haiku-claude-sqlverify-104x3/trial1'}


def final_value(ans):
    a = ans or ''
    m = re.search(r'(?im)^\s*(?:\*\*)?\s*(?:final\s+)?answer\s*[:：]\s*(.+)$', a)
    s = m.group(1) if m else None
    if not s:
        b = re.search(r'\*\*(.+?)\*\*', a)
        s = b.group(1) if b else (a.strip().splitlines() or [''])[0]
    s = re.sub(r'[*`$,]', '', s).strip().lower()
    nums = re.findall(r'-?\d+(?:\.\d+)?', s)
    return (nums[0] if nums and len(s) < 40 else s[:60])


def main(out):
    data = {}
    for name, rel in RUNS.items():
        for r in csv.DictReader(open(ROOT / 'results' / rel / 'runs.csv')):
            data.setdefault((r['dataset'], int(r['query'])), {})[name] = (r['passed'] == 'True', final_value(r.get('answer', '')))
    sys_wrong = unstable = 0
    lines = ['# Do wrong answers repeat across the five Haiku runs?', '',
             'Final value per run (wrong runs only; `=` marks a right run). Generated by `experiments/answer_recurrence.py`.', '',
             '| Question | Right in | t1 | t2 | fdj | docetl | sqlverify | Pattern |', '|---|---|---|---|---|---|---|---|']
    patterns = Counter()
    for k in sorted(data):
        runs = data[k]
        wrong = [v for p, v in runs.values() if not p]
        if len(wrong) < 2: continue
        top, n = Counter(wrong).most_common(1)[0]
        pat = 'same wrong value' if n == len(wrong) else ('mostly the same' if n >= 0.6 * len(wrong) else 'different wrong values')
        patterns[pat] += 1
        right = sum(p for p, _ in runs.values())
        if right == 0:
            cells = [('=' if runs[r][0] else runs[r][1][:28]) for r in RUNS]
            lines.append(f'| {k[0]} q{k[1]} | {right}/5 | ' + ' | '.join(c.replace('|', '/') for c in cells) + f' | {pat} |')
    lines += ['', 'Questions wrong in at least two runs, by pattern: ' + ', '.join(f'{p}: {n}' for p, n in patterns.most_common()), '']
    Path(out).write_text('\n'.join(lines) + '\n'); print('\n'.join(lines))


if __name__ == '__main__':
    main(sys.argv[1])
