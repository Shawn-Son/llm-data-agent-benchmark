"""Statistics over the five Haiku runs (baseline trials 1-2, fdj, docetl, sqlverify) on the same 104 questions.

    python experiments/stats_methods.py        # writes results/method-analysis/STATS.md and stats.json

1. Accuracy with Wilson 95% intervals; exact McNemar tests of each condition against each baseline trial.
2. Run-to-run noise: questions whose prompt and handling were identical to the baseline (untouched by the method)
   are five draws of the same condition; their per-question pass rate gives the noise floor.
3. Per-question pass counts over five runs: stable right, stable wrong, flaky.
4. Effort: tokens, cost and duration per condition, overall and on the questions each method acted on.
5. Review categories: Haiku both-runs-wrong questions across the five runs.
"""
from __future__ import annotations
import csv, json, math, statistics
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / 'results'
OUT = RES / 'method-analysis'
METHODS = ('fdj', 'docetl', 'sqlverify')


def load(path):
    return {(r['dataset'], int(r['query'])): r for r in csv.DictReader(open(path))}


def wilson(k, n, z=1.96):
    p = k / n; d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d; h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return c - h, c + h


def mcnemar_exact(b, c):
    """Two-sided exact McNemar p-value from the discordant counts b (only A right) and c (only B right)."""
    n = b + c
    if n == 0: return 1.0
    k = min(b, c)
    p = sum(math.comb(n, i) for i in range(0, k + 1)) / 2 ** n
    return min(1.0, 2 * p)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    runs = {'baseline_t1': load(RES / 'haiku-claude-104x3/trial1/runs.csv'), 'baseline_t2': load(RES / 'haiku-claude-104x3/trial2/runs.csv')}
    for m in METHODS: runs[m] = load(RES / f'haiku-claude-{m}-104x3/trial1/method_runs.csv')
    keys = sorted(runs['baseline_t1'])
    ok = {name: {k: r[k]['passed'] == 'True' for k in keys} for name, r in runs.items()}
    acted = {m: {k for k, r in runs[m].items() if (r.get('round2_ran') == 'True' if m == 'sqlverify' else r.get('method_inputs_staged') == 'True')} for m in METHODS}
    stats = {}
    md = ['# Statistics over the five Haiku runs', '',
          'Runs: baseline trials 1-2 (description + hints) and one trial each of fdj, docetl, sqlverify. Same 104 questions,',
          'same validators. Generated by `experiments/stats_methods.py`.', '']

    # 1. accuracy and McNemar
    md += ['## 1. Accuracy and paired tests', '', '| Run | Correct | Accuracy | Wilson 95% CI | vs baseline t1: only run right / only t1 right, McNemar p | vs baseline t2: same |', '|---|---|---|---|---|---|']
    stats['accuracy'] = {}
    for name in runs:
        k = sum(ok[name].values()); lo, hi = wilson(k, len(keys))
        cells = []
        for b in ('baseline_t1', 'baseline_t2'):
            if name == b: cells.append('-'); continue
            x = sum(1 for q in keys if ok[name][q] and not ok[b][q]); y = sum(1 for q in keys if ok[b][q] and not ok[name][q])
            cells.append(f'{x} / {y}, p = {mcnemar_exact(x, y):.2f}')
        md.append(f'| {name} | {k} | {k / len(keys):.1%} | {lo:.1%}-{hi:.1%} | {cells[0]} | {cells[1]} |')
        stats['accuracy'][name] = {'correct': k, 'ci95': [lo, hi]}
    md += ['', 'No run differs from either baseline trial at p < 0.05; the two baseline trials themselves differ by '
           f"{sum(1 for q in keys if ok['baseline_t1'][q] != ok['baseline_t2'][q])} discordant questions.", '']

    # 2. noise floor from untouched questions
    md += ['## 2. Noise floor from untouched questions', '',
           'On questions a method did not touch, the condition run is an independent draw of the baseline condition.', '',
           '| Run | Untouched questions | Correct (run / t1 / t2) | Discordant with t1 | Discordant with t2 |', '|---|---|---|---|---|']
    stats['untouched'] = {}
    for m in METHODS:
        u = [q for q in keys if q not in acted[m]]
        dis = [sum(1 for q in u if ok[m][q] != ok[b][q]) for b in ('baseline_t1', 'baseline_t2')]
        md.append(f"| {m} | {len(u)} | {sum(ok[m][q] for q in u)} / {sum(ok['baseline_t1'][q] for q in u)} / {sum(ok['baseline_t2'][q] for q in u)} | {dis[0]} | {dis[1]} |")
        stats['untouched'][m] = {'n': len(u), 'discordant': dis}
    allu = [q for q in keys if not any(q in acted[m] for m in METHODS)]
    rates = [sum(ok[n][q] for n in runs) / 5 for q in allu]
    flaky = [q for q in allu if 0 < sum(ok[n][q] for n in runs) < 5]
    var = sum(r * (1 - r) for r in rates)   # expected variance of the correct count of one run on these questions
    md += ['', f'Questions untouched by every method: {len(allu)}. Across the five runs {len(flaky)} of them are flaky (right in 1-4 runs).',
           f'Treating each question as Bernoulli with its five-run pass rate, one run\'s correct count on these {len(allu)} questions has',
           f'SD {math.sqrt(var):.1f}; the difference between two independent runs has SD {math.sqrt(2 * var):.1f} questions.', '']
    stats['noise'] = {'untouched_by_all': len(allu), 'flaky': len(flaky), 'sd_one_run': math.sqrt(var), 'sd_difference': math.sqrt(2 * var)}

    # 3. per-question stability
    cnt = {q: sum(ok[n][q] for n in runs) for q in keys}
    hist = Counter(cnt.values())
    md += ['## 3. Per-question pass counts over five runs', '', '| Right in k of 5 runs | Questions |', '|---|---|']
    md += [f'| {k} | {hist.get(k, 0)} |' for k in range(6)]
    never = sorted(q for q in keys if cnt[q] == 0)
    by_ds = defaultdict(list)
    for d, q in never: by_ds[d].append(q)
    md += ['', f'Never right ({len(never)}): ' + '; '.join(f'{d} q' + ','.join(map(str, qs)) for d, qs in sorted(by_ds.items())), '']
    stats['pass_count_histogram'] = {str(k): hist.get(k, 0) for k in range(6)}
    stats['never_right'] = [f'{d} q{q}' for d, q in never]

    # per dataset
    md += ['### Per dataset (correct answers)', '', '| Dataset | n | t1 | t2 | fdj | docetl | sqlverify | 5-run mean |', '|---|---|---|---|---|---|---|---|']
    for d in sorted({q[0] for q in keys}):
        qs = [q for q in keys if q[0] == d]
        vals = [sum(ok[n][q] for q in qs) for n in runs]
        md.append(f'| {d} | {len(qs)} | ' + ' | '.join(map(str, vals)) + f' | {statistics.mean(vals):.1f} |')
    md.append('')

    # 4. effort
    def num(r, f):
        try: return float(r.get(f) or 0)
        except ValueError: return 0.0
    md += ['## 4. Effort', '', '| Run | Agent cost (USD) | Input tokens (M) | Output tokens (M) | Agent time (h, summed) | Median time per question (s) |', '|---|---|---|---|---|---|']
    stats['effort'] = {}
    for name, r in runs.items():
        c = sum(num(r[q], 'estimated_cost_usd') for q in keys); i = sum(num(r[q], 'input_tokens') for q in keys)
        o = sum(num(r[q], 'output_tokens') for q in keys); t = [num(r[q], 'duration_s') for q in keys]
        md.append(f'| {name} | {c:.2f} | {i / 1e6:.1f} | {o / 1e6:.2f} | {sum(t) / 3600:.1f} | {statistics.median(t):.0f} |')
        stats['effort'][name] = {'cost': c, 'input_tokens': i, 'output_tokens': o, 'hours': sum(t) / 3600}
    md += ['', 'On the questions each method acted on (same questions in the baseline):', '',
           '| Method | Questions | Cost: method run vs baseline mean | Output tokens (K): method vs baseline mean | Time (min, summed): method vs baseline mean |', '|---|---|---|---|---|']
    for m in METHODS:
        qs = sorted(acted[m])
        f = lambda name, fld: sum(num(runs[name][q], fld) for q in qs)
        bm = lambda fld: (f('baseline_t1', fld) + f('baseline_t2', fld)) / 2
        md.append(f"| {m} | {len(qs)} | {f(m, 'estimated_cost_usd'):.2f} vs {bm('estimated_cost_usd'):.2f} | "
                  f"{f(m, 'output_tokens') / 1e3:.0f} vs {bm('output_tokens') / 1e3:.0f} | {f(m, 'duration_s') / 60:.0f} vs {bm('duration_s') / 60:.0f} |")
    md.append('')

    # 5. review categories
    cats = {}
    for r in csv.DictReader(open(RES / 'failure-review/both_runs_wrong.csv')):
        if r['model'] == 'haiku': cats[(r['dataset'], int(r['query'].replace('query', '')))] = r['primary']
    md += ['## 5. Haiku both-runs-wrong questions (review category) across the new runs', '',
           '| Category | Questions | Right in fdj / docetl / sqlverify | Questions right in at least one new run |', '|---|---|---|---|']
    stats['categories'] = {}
    for c in sorted(set(cats.values())):
        qs = [q for q, v in cats.items() if v == c]
        r3 = [sum(ok[m][q] for q in qs) for m in METHODS]
        any_ = [f'{d} q{q}' for d, q in sorted(qs) if any(ok[m][(d, q)] for m in METHODS)]
        md.append(f'| {c} | {len(qs)} | {r3[0]} / {r3[1]} / {r3[2]} | {", ".join(any_) or "-"} |')
        stats['categories'][c] = {'n': len(qs), 'right': dict(zip(METHODS, r3)), 'right_somewhere': any_}
    md += ['', 'A both-runs-wrong question that a new run gets right is evidence of a method only if the method acted on it;',
           'see the noise floor above and docs/METHOD_ANALYSIS.md section 2.', '']
    (OUT / 'STATS.md').write_text('\n'.join(md) + '\n')
    (OUT / 'stats.json').write_text(json.dumps(stats, indent=1, default=str) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
